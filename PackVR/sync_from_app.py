#!/usr/bin/env python3
"""
Copies what the AR page shares with the Android app, so the foil looks match exactly:
  - the foil shader core (CardCollection/app/src/main/res/raw/holo_core.agsl)
  - the GLSL wrapper pieces from HoloShaders.kt (PREFIX, EXTRAS, fragment main)
  - the synthesised pack sounds (res/raw/pack_*.wav)
Run after changing the app's shaders or sounds:  python3 PackVR/sync_from_app.py
The Android app itself is never modified by this.
"""
import os, re, shutil, sys

here = os.path.dirname(os.path.abspath(__file__))
app = os.path.join(here, "..", "CardCollection", "app", "src", "main")
kt = open(os.path.join(app, "java", "com", "senjumomo", "cards", "holo", "HoloShaders.kt")).read()
core = open(os.path.join(app, "res", "raw", "holo_core.agsl")).read()

def raw_string(after):
    i = kt.index(after) + len(after)
    j = kt.index('"""', i)
    return kt[i:j]

prefix = raw_string('private const val PREFIX = """')
extras = raw_string('private const val EXTRAS = """')
main = raw_string('fun fragment(core: String): String = PREFIX + core + EXTRAS + """')

def js(s):
    return "`" + s.replace("\\", "\\\\").replace("`", "\\`").replace("${", "\\${") + "`"

out = "// GENERATED by sync_from_app.py from the Android app's shaders. Do not edit by hand.\n"
out += "export const PREFIX = %s;\nexport const CORE = %s;\nexport const EXTRAS = %s;\nexport const MAIN = %s;\n" % (js(prefix), js(core), js(extras), js(main))
os.makedirs(os.path.join(here, "gen"), exist_ok=True)
open(os.path.join(here, "gen", "holo_shaders.js"), "w").write(out)

os.makedirs(os.path.join(here, "sounds"), exist_ok=True)
n = 0
for f in sorted(os.listdir(os.path.join(app, "res", "raw"))):
    if f.startswith("pack_") and f.endswith(".wav"):
        shutil.copy(os.path.join(app, "res", "raw", f), os.path.join(here, "sounds", f)); n += 1
print("shaders written; %d sounds copied" % n)
